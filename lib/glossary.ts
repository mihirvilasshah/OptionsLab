export function searchGlossary(query: string, level: GlossaryLevel | "All", category: string | "All") {
  const normalized = query.trim().toLowerCase();
  return GLOSSARY.filter((term) => {
    const matchesQuery =
      !normalized ||
      term.term.toLowerCase().includes(normalized) ||
      term.definition.toLowerCase().includes(normalized) ||
      term.example.toLowerCase().includes(normalized);
    const matchesLevel = level === "All" || term.level === level;
    const matchesCategory = category === "All" || term.category === category;
    return matchesQuery && matchesLevel && matchesCategory;
  });
}
